
import numpy as np
from scipy.linalg import eigh
import matplotlib.pyplot as plt


# ============================================================
# BASIS SET AND NUMERICAL PARAMETERS
# ============================================================

alpha_all = np.array([
    0.298073,
    1.242567,
    5.782948,
    38.474970
])

HA_TO_EV = 27.211386
Z = 3  # Lithium nuclear charge

r = np.linspace(1e-6, 10.0, 2000)

tol = 1e-8
max_iter = 100
mixing = 0.3


# ============================================================
# ANALYTICAL MATRIX ELEMENTS
# ============================================================

def build_matrices(alpha, Z):

    P = len(alpha)

    S = np.zeros((P, P))
    T = np.zeros((P, P))
    V_ext = np.zeros((P, P))

    for p in range(P):
        for q in range(P):

            beta = alpha[p] + alpha[q]

            S[p, q] = (np.pi / beta)**(3/2)

            T[p, q] = (
                3 * alpha[p] * alpha[q] * np.pi**(3/2)
                / beta**(5/2)
            )

            V_ext[p, q] = -2 * np.pi * Z / beta

    return S, T, V_ext


# ============================================================
# SCF FUNCTION
# ============================================================

def run_scf(P):

    if P < 2 or P > len(alpha_all):
        raise ValueError("For lithium, P must be between 2 and 4.")

    # Select the first P basis functions
    alpha = alpha_all[:P]

    # One-electron matrices
    S, T, V_ext = build_matrices(alpha, Z)
    h = T + V_ext

    # --------------------------------------------------------
    # Construct the two occupied orbitals
    # Coefficients are stored one orbital per row
    # --------------------------------------------------------

    def build_orbital(C):

        phi = np.zeros((2, len(r)))

        for i in range(2):
            for p in range(P):
                phi[i] += C[i, p] * np.exp(-alpha[p] * r**2)

        return phi

    # --------------------------------------------------------
    # Hartree potential generated by the total density
    # --------------------------------------------------------

    def hartree_potential(n):

        VH = np.zeros_like(r)

        for k in range(len(r)):

            denominator = np.maximum(r[k], r)
            integrand = r**2 * n / denominator

            VH[k] = 4 * np.pi * np.trapezoid(
                integrand, r
            )

        return VH

    # --------------------------------------------------------
    # Hartree matrix
    # --------------------------------------------------------

    def hartree_matrix(VH):

        V_H = np.zeros((P, P))

        for p in range(P):
            for q in range(P):

                chi_p = np.exp(-alpha[p] * r**2)
                chi_q = np.exp(-alpha[q] * r**2)

                integrand = (
                    4 * np.pi * r**2
                    * chi_p * VH * chi_q
                )

                V_H[p, q] = np.trapezoid(integrand, r)

        return V_H

    # --------------------------------------------------------
    # Initial guess
    # --------------------------------------------------------

    C_old = np.zeros((2, P))
    C_old[0, 0] = 1.0
    C_old[1, 1] = 1.0

    # Normalize each orbital with respect to S
    for i in range(2):
        norm = np.sqrt(C_old[i] @ S @ C_old[i])
        C_old[i] /= norm

    phi_old = build_orbital(C_old)

    # Lithium configuration: 1s^2 2s^1
    n_old = (
        2 * np.abs(phi_old[0])**2
        + np.abs(phi_old[1])**2
    )

    # --------------------------------------------------------
    # SCF iterations
    # --------------------------------------------------------

    diff = 1.0
    iteration = 0
    energy_history = []

    while diff > tol and iteration < max_iter:

        # Potential from the current density
        VH = hartree_potential(n_old)
        V_H = hartree_matrix(VH)

        # Effective Hamiltonian
        H = h + V_H

        # Generalized eigenvalue problem
        eigenvalues, eigenvectors = eigh(H, S)

        # First two orbitals, stored as rows
        C_new = eigenvectors[:, :2].T

        # Construct orbitals and new density
        phi_new = build_orbital(C_new)

        n_new = (
            2 * np.abs(phi_new[0])**2
            + np.abs(phi_new[1])**2
        )

        # Density convergence criterion
        diff = np.max(np.abs(n_new - n_old))

        # One-electron contribution to the total energy
        E_one = (
            2 * (C_new[0] @ h @ C_new[0])
            + (C_new[1] @ h @ C_new[1])
        )

        # Hartree contribution
        VH_new = hartree_potential(n_new)

        J = np.trapezoid(
            4 * np.pi * r**2 * n_new * VH_new,
            r
        )

        # Total Hartree energy
        E_total = E_one + 0.5 * J

        energy_history.append(E_total)

        # Density mixing for SCF stability
        n_old = (
            (1 - mixing) * n_old
            + mixing * n_new
        )

        C_old = C_new.copy()

        iteration += 1

    # --------------------------------------------------------
    # Final results
    # --------------------------------------------------------

    # Reconstruct the final orbitals and density
    phi_final = build_orbital(C_old)

    density_final = (
        2 * np.abs(phi_final[0])**2
        + np.abs(phi_final[1])**2
    )

    radial_density = 4 * np.pi * r**2 * density_final

    # Electron count from the radial density
    electron_count = np.trapezoid(radial_density, r)

    return {
        "P": P,
        "energy": E_total,
        "r": r.copy(),
        "phi": phi_final,
        "density": density_final,
        "radial_density": radial_density,
        "energy_history": energy_history,
        "iterations": iteration,
        "converged": diff <= tol,
        "electron_count": electron_count
    }


# ============================================================
# RUN CALCULATIONS FOR DIFFERENT BASIS SIZES
# ============================================================

results = [run_scf(P) for P in range(2, 5)]


# ============================================================
# 1. FINAL ENERGIES IN eV
# ============================================================

E_ref = -7.4780603  # Lithium ground-state reference, Hartree

print("FINAL ENERGIES")
print("-" * 75)

for result in results:

    P = result["P"]
    E = result["energy"]
    E_eV = E * HA_TO_EV
    error = abs(E - E_ref) * HA_TO_EV

    print(
        f"P = {P}: "
        f"E = {E_eV:.6f} eV, "
        f"error = {error:.6f} eV, "
        f"iterations = {result['iterations']}, "
        f"converged = {result['converged']}"
    )

# Select the energy closest to the reference
best_result = min(
    results,
    key=lambda result: abs(result["energy"] - E_ref)
)

P_best = best_result["P"]
r = best_result["r"]
phi = best_result["phi"]
density = best_result["density"]
radial_density = best_result["radial_density"]

print("\nSELECTED RESULT")
print(f"P = {P_best}")
print(f"Energy = {best_result['energy'] * HA_TO_EV:.6f} eV")
print(f"Integrated electron count = {best_result['electron_count']:.6f}")


# ============================================================
# 2. PLOT THE 1s AND 2s ORBITALS
# ============================================================

plt.figure()
plt.plot(r, phi[0], label="1s")
plt.plot(r, phi[1], label="2s")
plt.xlabel("r (a.u.)")
plt.ylabel("Orbital")
plt.title(f"Li orbitals (P = {P_best})")
plt.legend()
plt.grid()
plt.tight_layout()
plt.show()


# ============================================================
# 3. PLOT THE TOTAL RADIAL ELECTRON DENSITY
# ============================================================

plt.figure()
plt.plot(r, radial_density)
plt.xlabel("r (a.u.)")
plt.ylabel(r"$4\pi r^2 n(r)$")
plt.title(f"Li radial electron density (P = {P_best})")
plt.grid()
plt.tight_layout()
plt.show()


# ============================================================
# 4. PLOT THE TOTAL ELECTRON DENSITY
# ============================================================

plt.figure()
plt.plot(r, density)
plt.xlabel("r (a.u.)")
plt.ylabel(r"$n(r)$")
plt.title(f"Li total electron density (P = {P_best})")
plt.grid()
plt.tight_layout()
plt.show()
